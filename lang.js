// Global language state
let currentLang = 'en';
try {
  // Versioned key ensures fresh session starts with 100% English
  const saved = localStorage.getItem('desert_outpost_lang_v10');
  if (saved === 'en' || saved === 'vi') {
    currentLang = saved;
  } else {
    currentLang = 'en';
    localStorage.setItem('desert_outpost_lang_v10', 'en');
    localStorage.setItem('desert_outpost_lang', 'en');
  }
} catch (e) {
  currentLang = 'en';
}

function t(key, fallback = '', vars = null) {
  const langDict = I18N[currentLang] || I18N['vi'];
  let str = (langDict && langDict[key] !== undefined) ? langDict[key] : ((I18N['vi'] && I18N['vi'][key] !== undefined) ? I18N['vi'][key] : (fallback || key));
  if (vars && typeof vars === 'object') {
    Object.keys(vars).forEach(k => {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return str;
}

function setLanguage(lang) {
  if (lang !== 'vi' && lang !== 'en') lang = 'vi';
  currentLang = lang;
  try {
    localStorage.setItem('desert_outpost_lang', lang);
  } catch(e) {}
  
  // Update DOM elements with data-i18n
  applyLanguageToDOM();

  // If game app is running, trigger its re-render
  if (typeof window !== 'undefined' && window.gameApp && typeof window.gameApp.refreshAllText === 'function') {
    window.gameApp.refreshAllText();
  }
}

function toggleLanguage() {
  const nextLang = currentLang === 'en' ? 'vi' : 'en';
  setLanguage(nextLang);
  return nextLang;
}

function applyLanguageToDOM() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = currentLang;

  // Update language button display
  const langBtn = document.getElementById('btn-lang-toggle');
  if (langBtn) {
    langBtn.innerHTML = currentLang === 'en' ? '🇬🇧 EN' : '🇻🇳 VI';
    langBtn.title = currentLang === 'en' ? 'Language: English (Click for Tiếng Việt)' : 'Ngôn ngữ: Tiếng Việt (Click for English)';
  }

  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const translated = t(key);
      if (translated && translated !== key) {
        el.textContent = translated;
      }
    }
  });

  // Update elements with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) {
      const translated = t(key);
      if (translated && translated !== key) {
        el.title = translated;
      }
    }
  });

  // Update elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      const translated = t(key);
      if (translated && translated !== key) {
        el.placeholder = translated;
      }
    }
  });
}

// Auto-run applyLanguageToDOM immediately and on DOMContentLoaded
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyLanguageToDOM());
  } else {
    applyLanguageToDOM();
  }
}

if (typeof window !== 'undefined') {
  window.t = t;
  window.setLanguage = setLanguage;
  window.toggleLanguage = toggleLanguage;
  window.applyLanguageToDOM = applyLanguageToDOM;
  window.currentLang = currentLang;
}
